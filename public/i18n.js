export const LANGS = { 'zh-Hans': '简体中文', 'zh-Hant': '繁體中文', en: 'English' };

export function detectLang() {
  const saved = localStorage.getItem('imghub.lang');
  if (saved && DICT[saved]) return saved;
  for (const l of navigator.languages || [navigator.language]) {
    const s = l.toLowerCase();
    if (s.startsWith('zh')) return /hant|tw|hk|mo/.test(s) ? 'zh-Hant' : 'zh-Hans';
    if (s.startsWith('en')) return 'en';
  }
  return 'en';
}

let lang = 'en';
export const getLang = () => lang;

export function setLang(l) {
  lang = DICT[l] ? l : 'en';
  localStorage.setItem('imghub.lang', lang);
  document.documentElement.lang = lang;
  document.title = t(document.body.dataset.title || 'title');
  applyI18n(document);
  document.dispatchEvent(new CustomEvent('langchange'));
}

// data-i18n → 文本；data-i18n-ph → placeholder；data-i18n-tip → title + aria-label
export function applyI18n(root) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
  for (const el of root.querySelectorAll('[data-i18n-tip]')) {
    el.title = t(el.dataset.i18nTip);
    el.setAttribute('aria-label', el.title);
  }
}

export function t(key, vars = {}) {
  const s = DICT[lang][key] ?? DICT.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}
